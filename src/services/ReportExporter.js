'use strict';

/**
 * Formats a saved Report as CSV or PDF (story 60). Pure formatting - the
 * figures come unchanged from the stored report data.
 */
const LABELS = {
  new_users: 'New users', new_idps: 'New IDPs', searches: 'Searches performed', views: 'IDP views',
  favourites: 'Favourites (shortlists)', enquiries: 'Enquiries',
};

function csvCell(value) {
  if (value === null || value === undefined) return '';
  const s = String(value);
  // Prevent spreadsheet formula injection and quote special characters
  const safe = /^[=+\-@\t\r]/.test(s) ? `'${s}` : s;
  return /[",\n]/.test(safe) ? `"${safe.replace(/"/g, '""')}"` : safe;
}

function slug(report) {
  return `designmatch-${report.report_type}-report-${report.period_start}_to_${report.period_end}`;
}

/** Normalised sections shared by both formats. */
function sections(report) {
  const d = report.data || {};
  const out = [];
  out.push({
    title: 'Summary',
    columns: ['Metric', 'This period', ...(d.previous_period ? ['Previous period', 'Change %'] : [])],
    rows: Object.keys(LABELS).map((k) => [
      LABELS[k], d.totals ? d.totals[k] : 0,
      ...(d.previous_period ? [d.previous_period.totals[k], d.growth && d.growth[k] === null ? 'new' : (d.growth ? d.growth[k] : '')] : []),
    ]),
  });
  if (d.new_users_by_role) {
    out.push({
      title: 'New users by role', columns: ['Role', 'New users'],
      rows: Object.entries(d.new_users_by_role).map(([role, n]) => [role, n]),
    });
  }
  if (d.daily_series && d.daily_series.length) {
    out.push({
      title: 'Daily breakdown', columns: ['Date', 'New users', 'New IDPs', 'Searches', 'Views', 'Favourites', 'Enquiries'],
      rows: d.daily_series.map((r) => [r.day, r.new_users, r.new_idps, r.searches, r.views, r.favourites, r.enquiries]),
    });
  }
  if (d.top_designers) {
    out.push({
      title: 'Top-performing designers', columns: ['Rank', 'Designer', 'Views', 'Favourites', 'Enquiries', 'Score'],
      rows: d.top_designers.map((r, i) => [i + 1, r.name, r.views, r.favourites, r.enquiries, r.score]),
    });
  }
  if (d.top_categories) {
    out.push({
      title: 'Top-performing categories', columns: ['Rank', 'Category', 'New IDPs', 'Views', 'Favourites', 'Enquiries', 'Score'],
      rows: d.top_categories.map((r, i) => [i + 1, r.name, r.new_idps, r.views, r.favourites, r.enquiries, r.score]),
    });
  }
  if (d.top_search_keywords) {
    out.push({
      title: 'Top search keywords', columns: ['Keyword', 'Searches'],
      rows: d.top_search_keywords.map((r) => [r.keyword, r.searches]),
    });
  }
  return out;
}

class ReportExporter {
  static toCSV(report) {
    const lines = [
      ['DesignMatch platform report'],
      ['Title', report.title],
      ['Report type', report.report_type],
      ['Period start', report.period_start],
      ['Period end', report.period_end],
      ['Generated at', new Date(report.created_at).toISOString()],
      ['Generated by', report.generated_by_name || ''],
      [],
    ];
    sections(report).forEach((s) => {
      lines.push([s.title], s.columns, ...s.rows, []);
    });
    const body = lines.map((row) => row.map(csvCell).join(',')).join('\r\n');
    return { body: `﻿${body}`, filename: `${slug(report)}.csv`, contentType: 'text/csv; charset=utf-8' };
  }

  static toPDF(report) {
    // Lazy-load so CSV export and the rest of the app work even if pdfkit is unavailable
    const PDFDocument = require('pdfkit');
    return new Promise((resolve, reject) => {
      const doc = new PDFDocument({ size: 'A4', margin: 48, info: { Title: report.title, Author: 'DesignMatch' } });
      const chunks = [];
      doc.on('data', (c) => chunks.push(c));
      doc.on('error', reject);
      doc.on('end', () => resolve({
        body: Buffer.concat(chunks), filename: `${slug(report)}.pdf`, contentType: 'application/pdf',
      }));

      doc.fontSize(9).fillColor('#8a7f72').text('DESIGNMATCH  |  PLATFORM REPORT');
      doc.moveDown(0.4).fontSize(20).fillColor('#2b2926').text(report.title);
      doc.moveDown(0.3).fontSize(10).fillColor('#5c574f')
        .text(`Period: ${report.period_start} to ${report.period_end}   |   Type: ${report.report_type}`)
        .text(`Generated: ${new Date(report.created_at).toISOString().replace('T', ' ').slice(0, 16)} UTC by ${report.generated_by_name || 'Platform Management'}`);

      sections(report).forEach((s) => {
        if (doc.y > 700) doc.addPage();
        doc.moveDown(1).fontSize(12).fillColor('#2b2926').text(s.title);
        doc.moveDown(0.3);
        const width = doc.page.width - 96;
        const colW = width / s.columns.length;
        const drawRow = (cells, bold) => {
          if (doc.y > 760) doc.addPage();
          const y = doc.y;
          doc.fontSize(8.5).fillColor(bold ? '#2b2926' : '#4a463f').font(bold ? 'Helvetica-Bold' : 'Helvetica');
          cells.forEach((c, i) => doc.text(String(c ?? ''), 48 + i * colW, y, { width: colW - 6, lineBreak: false, ellipsis: true }));
          doc.y = y + 14;
          doc.x = 48;
        };
        drawRow(s.columns, true);
        doc.moveTo(48, doc.y - 3).lineTo(48 + width, doc.y - 3).strokeColor('#d9d2c7').stroke();
        if (!s.rows.length) drawRow(['No activity in this period'], false);
        s.rows.forEach((r) => drawRow(r, false));
        doc.font('Helvetica');
      });
      doc.moveDown(1.5).fontSize(7.5).fillColor('#8a7f72')
        .text('Engagement score = views + 3 x favourites + 5 x enquiries. All figures are calculated from platform records.', 48);
      doc.end();
    });
  }
}

module.exports = ReportExporter;
module.exports.csvCell = csvCell;
module.exports.sections = sections;
